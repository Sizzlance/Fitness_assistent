def generate_detailed_workout_plan(bmi, age, gender, goal, body_type, fitness_level):
    """Расширенная генерация плана тренировок"""
    plan = {
        "description": "",
        "workouts": [],
        "nutrition": "",
        "schedule": {},
        "tips": []
    }

    if bmi < 18.5:
        plan["description"] = "Программа для набора мышечной массы"
        plan["workouts"] = [
            "🏋️‍♂️ Базовые упражнения: приседания со штангой, жим лежа, становая тяга",
            "💪 Изолирующие упражнения: подъемы на бицепс, разгибания на трицепс",
            f"🔢 {3 if fitness_level == 'Начинающий' else 4} подхода по 8-12 повторений"
        ]
        plan["nutrition"] = "🍗 Питание с профицитом калорий (белок: 2г/кг веса)"
        plan["schedule"] = {
            "Понедельник": "Грудь + Трицепс",
            "Среда": "Спина + Бицепс",
            "Пятница": "Ноги + Плечи"
        }
        plan["tips"].append("Увеличивайте вес постепенно на 2-5% в неделю")

    elif 18.5 <= bmi < 25:
        if goal == "Похудение":
            plan["description"] = "Программа для снижения веса"
            plan["workouts"] = [
                "🏃‍♂️ Кардио: интервальный бег 30 мин (1:1 работа/отдых)",
                "🏋️‍♀️ Круговые тренировки с умеренными весами",
                "🧘‍♂️ Растяжка после каждой тренировки"
            ]
            plan["nutrition"] = "🥦 Дефицит калорий 10-15%, акцент на овощи и белок"
            plan["schedule"] = {
                "Понедельник": "ВИИТ + Силовая (верх тела)",
                "Среда": "Кардио 45 мин",
                "Пятница": "ВИИТ + Силовая (низ тела)",
                "Суббота": "Длительное кардио (60 мин)"
            }
            plan["tips"].append("Следите за пульсом в зоне жиросжигания (60-70% от максимума)")

        elif goal == "Набор массы":
            plan["description"] = "Программа для набора качественной массы"
            plan["workouts"] = [
                "🏋️‍♂️ Тяжелые базовые упражнения 4-5 подходов по 6-8 повторений",
                "🔥 Суперсеты для увеличения интенсивности",
                "🔄 Прогрессия нагрузок каждую неделю"
            ]
            plan["nutrition"] = "🍚 Профицит 300-500 ккал, 2.5г белка/кг веса"
            plan["schedule"] = {
                "Понедельник": "Грудь + Бицепс",
                "Вторник": "Кардио 20 мин",
                "Четверг": "Спина + Трицепс",
                "Пятница": "Ноги + Плечи"
            }
            plan["tips"].append("Делайте 2-3 минуты отдыха между подходами")

        else:
            plan["description"] = "Программа для поддержания формы"
            plan["workouts"] = [
                "⚖️ Баланс силовых и кардио тренировок",
                "🧩 Функциональные упражнения",
                "🤸‍♀️ Работа над мобильностью суставов"
            ]
            plan["nutrition"] = "🥑 Сбалансированное питание (БЖУ: 30/30/40)"
            plan["schedule"] = {
                "Понедельник": "Верх тела",
                "Среда": "Кардио + Коре",
                "Пятница": "Низ тела",
                "Воскресенье": "Активный отдых (йога, плавание)"
            }

    else:
        plan["description"] = "Программа для снижения веса и улучшения здоровья"
        plan["workouts"] = [
            "🚶‍♂️ Низкоударное кардио (ходьба, велосипед, эллипс)",
            "💧 Аквааэробика (при проблемах с суставами)",
            "🧘‍♀️ Упражнения на растяжку и мобильность"
        ]
        plan["nutrition"] = "🥬 Дефицит 15-20%, упор на клетчатку и белок"
        plan["schedule"] = {
            "Понедельник": "Ходьба 45 мин",
            "Среда": "Круговая тренировка с весом тела",
            "Пятница": "Плавание/Аквааэробика",
            "Суббота": "Длительная ходьба 60+ мин"
        }
        plan["tips"].append("Начинайте с малых нагрузок и постепенно увеличивайте")

    if body_type == "Груша":
        plan["workouts"].append("🔹 Акцент на упражнения для верхней части тела (жимы, тяги)")
        plan["tips"].append("Для баланса фигуры развивайте плечи и спину")
    elif body_type == "Яблоко":
        plan["workouts"].append("🔹 Упражнения для кора и кардио для сжигания висцерального жира")
        plan["tips"].append("Избегайте упражнений в наклоне при проблемах с позвоночником")
    elif body_type == "Песочные часы":
        plan["tips"].append("Поддерживайте пропорции, равномерно развивая все группы мышц")

    if fitness_level == "Начинающий":
        plan["workouts"].insert(0, "🌟 Начинайте с 2-3 тренировок в неделю по 30-40 минут")
        plan["tips"].append("Сначала освойте технику, затем увеличивайте вес")
    elif fitness_level == "Продвинутый":
        plan["workouts"].append("🔥 Добавьте дроп-сеты и форсированные повторения")
        plan["tips"].append("Меняйте программу каждые 6-8 недель для прогресса")

    return plan
